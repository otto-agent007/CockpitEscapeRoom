import { afterEach, describe, expect, it, vi } from 'vitest'
import { createMarsArcadeShortcut, MARS_ARCADE_HOLD_MS } from './marsArcadeShortcut'

afterEach(() => vi.useRealTimers())
function setup() {
  vi.useFakeTimers()
  const activate = vi.fn()
  const shortcut = createMarsArcadeShortcut(activate)
  return { activate, shortcut }
}
describe('continuous T+M+B hold', () => {
  it.each([['t', 'm', 'b'], ['b', 't', 'm'], ['m', 'b', 't']])('starts the hold only when all letters overlap (%s/%s/%s)', (...keys) => {
    const { activate, shortcut } = setup()
    shortcut.down(keys[0]!)
    vi.advanceTimersByTime(10_000)
    shortcut.down(keys[1]!)
    vi.advanceTimersByTime(10_000)
    expect(activate).not.toHaveBeenCalled()
    shortcut.down(keys[2]!)
    vi.advanceTimersByTime(MARS_ARCADE_HOLD_MS - 1)
    expect(activate).not.toHaveBeenCalled()
    vi.advanceTimersByTime(1)
    expect(activate).toHaveBeenCalledOnce()
  })
  it('cancels on early release and requires another complete hold', () => {
    const { activate, shortcut } = setup()
    for (const key of ['t', 'm', 'b']) shortcut.down(key)
    vi.advanceTimersByTime(MARS_ARCADE_HOLD_MS - 1)
    shortcut.up('m')
    vi.advanceTimersByTime(10_000)
    expect(activate).not.toHaveBeenCalled()
    shortcut.down('m')
    vi.advanceTimersByTime(MARS_ARCADE_HOLD_MS)
    expect(activate).toHaveBeenCalledOnce()
  })
  it('does not extend timing on repeats or activate twice while held', () => {
    const { activate, shortcut } = setup()
    for (const key of ['T', 'M', 'B']) shortcut.down(key)
    vi.advanceTimersByTime(500)
    shortcut.down('T')
    vi.advanceTimersByTime(MARS_ARCADE_HOLD_MS - 500)
    expect(activate).toHaveBeenCalledOnce()
    shortcut.down('B')
    shortcut.up('t')
    shortcut.down('t')
    vi.advanceTimersByTime(10_000)
    expect(activate).toHaveBeenCalledOnce()
    for (const key of ['t', 'm', 'b']) shortcut.up(key)
    for (const key of ['t', 'm', 'b']) shortcut.down(key)
    vi.advanceTimersByTime(MARS_ARCADE_HOLD_MS)
    expect(activate).toHaveBeenCalledTimes(2)
  })
  it('reset cancels timing and clears all held keys', () => {
    const { activate, shortcut } = setup()
    for (const key of ['t', 'm', 'b']) shortcut.down(key)
    vi.advanceTimersByTime(1000)
    shortcut.reset()
    vi.advanceTimersByTime(10_000)
    shortcut.down('b')
    vi.advanceTimersByTime(10_000)
    expect(activate).not.toHaveBeenCalled()
  })
  it('ignores unrelated letters', () => {
    const { activate, shortcut } = setup()
    for (const key of ['t', 'm', 'x']) shortcut.down(key)
    vi.advanceTimersByTime(10_000)
    expect(activate).not.toHaveBeenCalled()
  })
})
